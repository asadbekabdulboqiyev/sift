// --- Security helpers -------------------------------------------------------

// sameOrigin reports whether the request's Origin header (when present)
// matches the host the request was sent to.
//
//   - No Origin header (curl, CLI clients, non-browser consumers): allowed.
//   - Origin present and its host equals r.Host: allowed — this covers the
//     localhost dev case because a browser connecting to
//     http://127.0.0.1:8888 sends Origin "http://127.0.0.1:8888", which
//     matches the Host header of the request it makes.
//   - Origin present with a different host, or a non-http(s) scheme (as a
//     cross-site WebSocket or fetch would carry): rejected.
func sameOrigin(r *http.Request) bool {
	origin := r.Header.Get("Origin")
	if origin == "" {
		return true // non-browser client
	}
	u, err := url.Parse(origin)
	if err != nil {
		return false
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return false
	}
	return strings.EqualFold(u.Host, r.Host)
}

// securityHeaders applies defense-in-depth response headers on every
// dashboard response. connect-src explicitly re-allows the same-origin
// WebSocket endpoint (ws/wss on r.Host) because 'self' matching for
// WebSockets is inconsistent across browsers.
//
// style-src allows 'unsafe-inline' on purpose. The certificate page previews
// the HTML report that ships inside a signed certificate, and that document
// carries its own <style> block and two style attributes. It is generated by
// this server from a signed assessment and rendered in a sandboxed iframe, so
// the alternative is a preview that looks broken. The width of the exception is
// deliberate and narrow:
//
//   - script-src stays 'self'. The report contains no script and none may run,
//     so inline CSS cannot escalate to code execution.
//   - img-src stays 'self' with data: only, so a malicious stylesheet has no
//     outbound URL to leak attribute values through.
//   - object-src is 'none' and base-uri is 'none'.
func securityHeaders(w http.ResponseWriter, r *http.Request) {
	h := w.Header()
	h.Set("X-Content-Type-Options", "nosniff")
	h.Set("X-Frame-Options", "DENY")
	h.Set("Referrer-Policy", "no-referrer")
	if r.TLS != nil {
		h.Set("Strict-Transport-Security", "max-age=31536000; includeSubDomains")
	}
	// The Host header is attacker-controlled in front of a proxy. Interpolating
	// it raw into a CSP directive would let a value such as
	// "x; script-src *" append a new directive and defeat the policy. Only a
	// syntactically valid host[:port] is admitted; anything else drops the
	// explicit WebSocket sources and falls back to 'self' alone.
	connectSrc := "connect-src 'self'"
	if host := safeCSPHost(r.Host); host != "" {
		connectSrc += fmt.Sprintf(" ws://%s wss://%s", host, host)
	}
	h.Set("Content-Security-Policy",
		"default-src 'self'; "+
			"script-src 'self'; "+
			"style-src 'self' 'unsafe-inline'; "+
			"img-src 'self' data:; "+
			"font-src 'self' data:; "+
			"object-src 'none'; "+
			"base-uri 'none'; "+
			"frame-ancestors 'self'; "+
			connectSrc)
}

// safeCSPHost returns host unchanged only when it is a syntactically valid
// host[:port] that can be placed verbatim inside a CSP source expression.
// Whitespace, quotes, semicolons, commas, slashes and other directive syntax
// are rejected. Invalid input returns "" so the caller omits the source rather
// than trying to escape it inside a header value.
func safeCSPHost(host string) string {
	if host == "" || len(host) > 255 {
		return ""
	}

	h, port, err := net.SplitHostPort(host)
	if err != nil {
		// No port component (or a malformed one): judge the whole value as host.
		h, port = host, ""
	}
	if port != "" {
		for _, c := range port {
			if c < '0' || c > '9' {
				return ""
			}
		}
	}
	if h == "" {
		return ""
	}

	if strings.HasPrefix(h, "[") && strings.HasSuffix(h, "]") {
		// IPv6 literal, e.g. [::1]:8888.
		if net.ParseIP(h[1:len(h)-1]) == nil {
			return ""
		}
		return host
	}
	if net.ParseIP(h) != nil {
		return host // IPv4 literal
	}
	for _, c := range h {
		if (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
			(c >= '0' && c <= '9') || c == '-' || c == '.' {
			continue
		}
		return ""
	}
	if strings.HasPrefix(h, ".") || strings.HasSuffix(h, ".") || strings.Contains(h, "..") {
		return ""
	}
	return host
}

// IsLoopbackAddr reports whether a listen address binds only to the
// loopback interface. ":port" or "0.0.0.0:port" bind every interface and
// report false; 127.0.0.1, ::1 and "localhost" report true. Used to warn
// when the dashboard control plane is exposed to the network.
func IsLoopbackAddr(addr string) bool {
	host := addr
	if h, _, err := net.SplitHostPort(addr); err == nil {
		host = h
	}
	if host == "" {
		return false // ":port" wildcard — all interfaces
	}
	return shared.IsLoopbackHost(host)
}
